#pragma once

// 快捷键/托盘触发截图，到"覆盖窗能收鼠标"之间有一段空窗：WinCap::onCreated 里是
// **同步抓屏**（GDI BitBlt + GetDIBits，整屏 50~300ms），抓完才 show()。空窗期桌面还是活的，
// 用户这一下拖动会落到下面的窗口上 —— 典型表现就是：
//   1) 按了快捷键却"一时间不能马上框选"（按下被下面的窗口吃掉了，覆盖窗永远收不到这次 press）；
//   2) 退出截图后发现浏览器网页里的文字被拖选了（浏览器接到了 down，按自己的逻辑一路拖选）。
// CaptureShield 在抓屏**之前**先铺一层"看不见但能收鼠标"的窗口，把空窗期的按下吃掉；
// 等覆盖窗 show() 之后再把这一下补交给它：还按着就从起点接着拖，已经松手就当成一次完整框选。
namespace CaptureShield
{
	// 铺盾牌：必须在开始抓屏之前调用（UI 线程）
	void arm();
	// 覆盖窗已经 show()：把空窗期的按下补交给它，然后撤掉盾牌
	void drain(HWND target);
}
